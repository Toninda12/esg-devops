CREATE SEQUENCE SEQ_RESIDUO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_RESIDUO (
    ID_RESIDUO INTEGER DEFAULT SEQ_RESIDUO.NEXTVAL NOT NULL,
    NM_RESIDUO VARCHAR2(100) NOT NULL,
    DS_RESIDUO VARCHAR2(100) NOT NULL,
    DS_INSTRUCAO_DESCARTE VARCHAR2(200) NOT NULL,
    DS_DESTINACAO VARCHAR2(100) NOT NULL,
    TP_RESIDUO VARCHAR2(100) NOT NULL,
    FL_PERIGOSO VARCHAR2(100) NOT NULL,
    DT_CADASTRO TIMESTAMP NOT NULL,

    CONSTRAINT PK_RESIDUO
        PRIMARY KEY (ID_RESIDUO)

);
