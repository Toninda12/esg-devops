CREATE SEQUENCE SEQ_USUARIO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_USUARIO (
    ID_USUARIO INTEGER DEFAULT SEQ_USUARIO.NEXTVAL NOT NULL,
    NM_USUARIO VARCHAR2(100) NOT NULL,
    DS_EMAIL VARCHAR2(50) NOT NULL,
    DS_SENHA VARCHAR2(50) NOT NULL,
    NR_TELEFONE VARCHAR2(50) NOT NULL,
    TP_PERFIL VARCHAR2(50) NOT NULL,
    DT_CADASTRO TIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIO
            PRIMARY KEY (ID_USUARIO),

        CONSTRAINT UK_USUARIO_EMAIL
            UNIQUE (DS_EMAIL)
);