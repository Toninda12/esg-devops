CREATE SEQUENCE SEQ_ALERTA
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_ALERTA (
    ID_ALERTA INTEGER DEFAULT SEQ_ALERTA.NEXTVAL NOT NULL,
    ID_PONTO_COLETA NUMBER(19) NOT NULL,
    DS_MENSAGEM VARCHAR2(200) NOT NULL,
    NR_PERCENTUAL_OCUPACAO NUMBER(3) NOT NULL,
    TP_ALERTA VARCHAR(30) NOT NULL,
    ST_ALERTA VARCHAR(30) NOT NULL,
    DT_ALERTA TIMESTAMP NOT NULL,
    DT_RESOLUCAO TIMESTAMP NOT NULL,

    CONSTRAINT PK_ALERTA
            PRIMARY KEY (ID_ALERTA),

        CONSTRAINT FK_ALERTA_PONTO
            FOREIGN KEY (ID_PONTO_COLETA)
            REFERENCES TB_PONTO_COLETA(ID_PONTO_COLETA)

);