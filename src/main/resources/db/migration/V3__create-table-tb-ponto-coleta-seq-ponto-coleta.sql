CREATE SEQUENCE SEQ_PONTO_COLETA
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_PONTO_COLETA (
    ID_PONTO_COLETA INTEGER DEFAULT SEQ_PONTO_COLETA.NEXTVAL NOT NULL,
    NM_PONTO_COLETA VARCHAR2(100) NOT NULL,
    DS_ENDERECO VARCHAR2(100) NOT NULL,
    NR_LATITUDE NUMBER(10,7) ,
    NR_LONGITUDE NUMBER(10,7) ,
    TP_RESIDUO VARCHAR2(30) NOT NULL,
    NR_CAPACIDADE_MAX_KG NUMBER(10,2) NOT NULL,
    NR_VOLUME_ATUAL_KG NUMBER(10,2) NOT NULL,
    NR_PERCENTUAL_ALERTA NUMBER(3) NOT NULL,
    ST_PONTO_COLETA VARCHAR2(30) NOT NULL,
    DT_CADASTRO TIMESTAMP NOT NULL,

    CONSTRAINT PK_PONTO_COLETA
        PRIMARY KEY (ID_PONTO_COLETA)

);