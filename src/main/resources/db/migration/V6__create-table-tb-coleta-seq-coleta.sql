

CREATE SEQUENCE SEQ_COLETA
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_COLETA (
    ID_COLETA INTEGER DEFAULT SEQ_COLETA.NEXTVAL NOT NULL,
    ID_PONTO_COLETA NUMBER(19) NOT NULL,
    ID_USUARIO NUMBER(19) NOT NULL,
    ID_RESIDUO NUMBER(19) ,
    NR_QUANTIDADE_KG NUMBER(10,2) NOT NULL,
    DS_OBSERVACAO VARCHAR2(200),
    TP_OPERACAO VARCHAR2(20) NOT NULL,
    DT_COLETA TIMESTAMP NOT NULL,

    CONSTRAINT PK_COLETA
            PRIMARY KEY (ID_COLETA),

        CONSTRAINT FK_COLETA_PONTO
            FOREIGN KEY (ID_PONTO_COLETA)
            REFERENCES TB_PONTO_COLETA(ID_PONTO_COLETA),

        CONSTRAINT FK_COLETA_USUARIO
            FOREIGN KEY (ID_USUARIO)
            REFERENCES TB_USUARIO(ID_USUARIO),

        CONSTRAINT FK_COLETA_RESIDUO
            FOREIGN KEY (ID_RESIDUO)
            REFERENCES TB_RESIDUO(ID_RESIDUO)

);
